import 'dart:io';
import 'dart:ui' as ui;

import 'package:clipback_frontend/shared/theme/assets.dart';
import 'package:crypto/crypto.dart';
import 'package:flutter_test/flutter_test.dart';

Future<ui.Image> _decode(String path, {int? width, int? height}) async {
  final codec = await ui.instantiateImageCodec(
    File(path).readAsBytesSync(),
    targetWidth: width,
    targetHeight: height,
  );
  final image = (await codec.getNextFrame()).image;
  codec.dispose();
  return image;
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('empty boxes share one unchanged Figma original', () async {
    expect(
      Assets.notificationEmptyIllustration,
      Assets.unclassifiedEmptyIllustration,
    );
    final bytes = File(Assets.unclassifiedEmptyIllustration).readAsBytesSync();
    expect(
      sha256.convert(bytes).toString(),
      '73b529416f2232b612211dc37a918af8691f05ccc29e3239061bf662a40ea693',
    );
    final image = await _decode(Assets.unclassifiedEmptyIllustration);
    expect(image.width, 1254);
    expect(image.height, 1254);
    image.dispose();
  });

  test('home derivative preserves the original export crop and shadow', () async {
    final bytes = File(Assets.homeEmptyIllustration).readAsBytesSync();
    // Generated by tool/generate_home_empty.py from the approved shared PNG.
    // Locks provenance as well as dimensions; a resized 71x82 cannot replace it.
    expect(
      sha256.convert(bytes).toString(),
      '44c9d543d1eb4d823368d7b544c5f66674d3daf20e8917160407377326171ce2',
    );
    final native = await _decode(Assets.homeEmptyIllustration);
    expect(native.width, 284);
    expect(native.height, 328);
    native.dispose();
    final before = await _decode('test/fixtures/empty_assets/home-before.png');
    final after = await _decode(
      Assets.homeEmptyIllustration,
      width: 71,
      height: 82,
    );
    final a = (await before.toByteData(
      format: ui.ImageByteFormat.rawRgba,
    ))!.buffer.asUint8List();
    final b = (await after.toByteData(
      format: ui.ImageByteFormat.rawRgba,
    ))!.buffer.asUint8List();
    var difference = 0;
    for (var i = 0; i < a.length; i++) {
      difference += (a[i] - b[i]).abs();
    }
    // Allows resampling antialiasing, while catching a smaller image due to
    // raw transparent margins, a shifted crop, or a missing silhouette shadow.
    expect(difference / a.length, lessThan(2));
    var shadowDifference = 0;
    for (var y = 78; y < 82; y++) {
      for (var x = 0; x < 71; x++) {
        final i = (y * 71 + x) * 4;
        shadowDifference += (a[i] - b[i]).abs();
      }
    }
    expect(shadowDifference / (4 * 71), lessThan(2));
    before.dispose();
    after.dispose();
  });
}
